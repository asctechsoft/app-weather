import { Injectable } from '@nestjs/common';
import { createHash, randomBytes, randomUUID } from 'crypto';
import { config } from '../config';
import { ApiError, badRequest } from '../common/errors';
import { isValidTimezone } from '../common/time';
import { Db } from '../db/db';

export interface Installation {
  installationId: string;
  platform: string;
  locale: string | null;
  timezone: string | null;
  tokenExpiresAt: string;
}

export interface IssuedToken {
  installationId: string;
  token: string;
  tokenExpiresAt: string;
}

const PLATFORMS = ['android', 'ios', 'web', 'windows', 'macos', 'linux'];
/** Tokens may be refreshed up to this long after expiry; afterwards the app re-registers. */
const REFRESH_GRACE_MS = 7 * 86_400_000;

export const hashToken = (token: string) => createHash('sha256').update(token, 'utf8').digest();

/**
 * Installation = anonymous app install. The bearer token is generated by the server, shown to
 * the client once and stored only as a SHA-256 hash. A random installation ID is never a credential.
 */
@Injectable()
export class InstallationsService {
  /** Short-lived auth cache so every request does not hit the database. */
  private readonly authCache = new Map<string, { inst: Installation; until: number }>();

  constructor(private readonly db: Db) {}

  private newToken(): string {
    return `swi_${randomBytes(32).toString('base64url')}`;
  }

  private expiry(): Date {
    return new Date(Date.now() + config.installationTokenTtlDays * 86_400_000);
  }

  async register(input: { platform?: string; appVersion?: string; locale?: string; timezone?: string }): Promise<IssuedToken> {
    if (!input.platform || !PLATFORMS.includes(input.platform)) throw badRequest('platform', 'validation.enum');
    if (!input.appVersion || !/^[0-9A-Za-z.+_-]{1,40}$/.test(input.appVersion)) throw badRequest('appVersion', 'validation.appVersion');
    const locale = input.locale && /^[a-z]{2}(-[A-Z]{2})?$/.test(input.locale) ? input.locale : null;
    const tz = input.timezone && isValidTimezone(input.timezone) ? input.timezone : null;
    const id = randomUUID();
    const token = this.newToken();
    const exp = this.expiry();
    await this.db.query(
      `INSERT INTO installations (installation_id, token_hash, token_expires_at, platform, app_version, locale, timezone)
       VALUES ($1,$2,$3,$4,$5,$6,$7)`,
      [id, hashToken(token), exp, input.platform, input.appVersion, locale, tz],
    );
    return { installationId: id, token, tokenExpiresAt: exp.toISOString() };
  }

  /** Returns the installation for a valid, unexpired, unrevoked token; otherwise throws 401. */
  async authenticate(token: string | undefined): Promise<Installation> {
    if (!token || !/^swi_[A-Za-z0-9_-]{43}$/.test(token)) throw new ApiError(401, 'UNAUTHENTICATED', 'error.unauthenticated');
    const key = hashToken(token).toString('hex');
    const hit = this.authCache.get(key);
    if (hit && hit.until > Date.now() && Date.parse(hit.inst.tokenExpiresAt) > Date.now()) return hit.inst;
    const row = await this.db.one<{ installation_id: string; platform: string; locale: string | null; timezone: string | null; token_expires_at: Date; revoked_at: Date | null }>(
      `UPDATE installations SET last_seen_at = now() WHERE token_hash = $1
       RETURNING installation_id, platform, locale, timezone, token_expires_at, revoked_at`,
      [hashToken(token)],
    );
    if (!row || row.revoked_at) throw new ApiError(401, 'UNAUTHENTICATED', 'error.unauthenticated');
    if (row.token_expires_at.getTime() <= Date.now()) throw new ApiError(401, 'TOKEN_EXPIRED', 'error.tokenExpired');
    const inst: Installation = {
      installationId: row.installation_id,
      platform: row.platform,
      locale: row.locale,
      timezone: row.timezone,
      tokenExpiresAt: row.token_expires_at.toISOString(),
    };
    this.authCache.set(key, { inst, until: Date.now() + 60_000 });
    if (this.authCache.size > 10_000) this.authCache.clear();
    return inst;
  }

  /** Rotates the token. Accepts a token expired for less than the grace period. */
  async refresh(oldToken: string | undefined): Promise<IssuedToken> {
    if (!oldToken) throw new ApiError(401, 'UNAUTHENTICATED', 'error.unauthenticated');
    const row = await this.db.one<{ installation_id: string; token_expires_at: Date; revoked_at: Date | null }>(
      `SELECT installation_id, token_expires_at, revoked_at FROM installations WHERE token_hash = $1`,
      [hashToken(oldToken)],
    );
    if (!row || row.revoked_at || row.token_expires_at.getTime() + REFRESH_GRACE_MS < Date.now()) {
      throw new ApiError(401, 'UNAUTHENTICATED', 'error.unauthenticated');
    }
    const token = this.newToken();
    const exp = this.expiry();
    await this.db.query(`UPDATE installations SET token_hash = $2, token_expires_at = $3, last_seen_at = now() WHERE installation_id = $1`, [row.installation_id, hashToken(token), exp]);
    this.authCache.delete(hashToken(oldToken).toString('hex'));
    return { installationId: row.installation_id, token, tokenExpiresAt: exp.toISOString() };
  }

  async updateProfile(inst: Installation, input: { locale?: string; timezone?: string; appVersion?: string }): Promise<void> {
    const locale = input.locale && /^[a-z]{2}(-[A-Z]{2})?$/.test(input.locale) ? input.locale : null;
    const tz = input.timezone && isValidTimezone(input.timezone) ? input.timezone : null;
    const ver = input.appVersion && /^[0-9A-Za-z.+_-]{1,40}$/.test(input.appVersion) ? input.appVersion : null;
    await this.db.query(
      `UPDATE installations SET locale = COALESCE($2, locale), timezone = COALESCE($3, timezone), app_version = COALESCE($4, app_version) WHERE installation_id = $1`,
      [inst.installationId, locale, tz, ver],
    );
    this.authCache.clear();
  }

  /**
   * Revokes the token and deletes server-side data of this installation (SW081): push tokens,
   * notification preferences and events cascade; feedback tickets are detached and keep their
   * own retention period; attachments owned by the installation cascade.
   */
  async deleteInstallation(inst: Installation): Promise<void> {
    await this.db.tx(async (c) => {
      await c.query(`UPDATE feedback SET installation_id = NULL WHERE installation_id = $1`, [inst.installationId]);
      await c.query(`DELETE FROM installations WHERE installation_id = $1`, [inst.installationId]);
    });
    this.authCache.clear();
  }
}
